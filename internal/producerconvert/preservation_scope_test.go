func TestNestedOriginalTestsReceivePreservationFilters(t *testing.T) {
	for _, parent := range []string{"tests", "skills/example/tests"} {
		for _, language := range []string{"python-registration", "python-collector", "python-assertion", "python-bypass", "shell", "go"} {
			t.Run(parent+"/"+language, func(t *testing.T) {
				root, opts := fleetFixture(t, fleetCaller)
				opts.Agent = "codex"
				name := parent + "/test_example.py"
				before := "# tessl install other/producer\ndef fail(failures, message):\n    failures.append(message)\ndef test_keep():\n    assert True\nTESTS = [test_keep]\n"
				after := strings.Replace(before, "# tessl install other/producer\n", "", 1)
				switch language {
				case "python-registration":
					after = strings.Replace(after, "TESTS = [test_keep]", "TESTS = []", 1)
				case "python-collector":
					after = strings.Replace(after, "failures.append(message)", "pass", 1)
				case "python-assertion":
					after = strings.Replace(after, "assert True", "pass", 1)
				case "python-bypass":
					after = strings.Replace(after, "def test_keep():", "@unittest.skip(\"weakened\")\ndef test_keep():", 1)
				case "shell":
					name = parent + "/test_example.sh"
					before = "#!/bin/sh\n# tessl install other/producer\nprintf original\n"
					after = "#!/bin/sh\nprintf weakened\n"
				case "go":
					name = parent + "/test_example.go"
					before = "// tessl install other/producer\npackage sample\nfunc testKeep() bool { return false }\n"
					after = "package sample\nfunc testKeep() bool { return true }\n"
				}
				put(t, root, name, before, 0644)
				original := treeAt(t, root)
				proposed := proposal{Edits: []proposedEdit{{Path: name, BeforeDigest: digest([]byte(before)), Action: "replace", Content: after}}}
				_, err := prepareWithProvider(context.Background(), opts, func(context.Context, string, string) (proposal, AgentRun, error) { return proposed, AgentRun{}, nil })
				if err == nil {
					t.Fatal("test weakening accepted")
				}
				if !matches(original, treeAt(t, root)) {
					t.Fatal("refusal changed source")
				}
			})
		}
	}
}

func TestRepositoryFormatsKeepOriginalBytesAndScope(t *testing.T) {
	for _, format := range []string{"ignore", "pyright", "rule"} {
		t.Run(format, func(t *testing.T) {
			root, opts := fleetFixture(t, fleetCaller)
			name, body := ".gitignore", "# Generated by tessl install; tessl.json remains foreign\n.tessl/\n.agents/\n!keep/.tessl/\n"
			switch format {
			case "pyright":
				name = "pyrightconfig.json"
				body = `{"include":[".github/scripts","skills/example/scripts","skills/example/tests"],"pythonVersion":"3.12","typeCheckingMode":"standard","reportMissingImports":"error"}`
				put(t, root, "skills/example/scripts/helper.py", "print('kept')\n", 0644)
				put(t, root, "skills/example/tests/test_keep.py", "assert True\n", 0644)
			case "rule":
				name = "rules/policy.md"
				body = "---\nalwaysApply: false\napplyTo: \"skills/example/** — when checking examples\"\ndescription: Example checks\n---\n# Policy\nKeep every independent check.\n"
				put(t, root, ".tessl-plugin/plugin.json", `{"name":"other/producer","version":"1.2.3","skills":["skills/example"],"rules":["rules/policy.md"]}`, 0644)
			}
			put(t, root, name, body, 0644)
			plan, err := Prepare(opts)
			if err != nil {
				t.Fatal(err)
			}
			if _, err = plan.Apply(); err != nil {
				t.Fatal(err)
			}
			got := treeAt(t, root)[name]
			if string(got.Content) != body || got.Mode != 0644 {
				t.Fatal("configuration bytes/mode changed")
			}
			if format == "rule" {
				// The existing manifest activation parser remains authoritative.
				if len(plan.Report.Artifacts) == 0 || !strings.Contains(read(t, root, "agent-plugin.yaml"), "skills/example/**") {
					t.Fatal("activation scope lost")
				}
			}
		})
	}
}

func TestOwnedReferenceOnlyContentCanBeProposed(t *testing.T) {
	root, opts := fleetFixture(t, fleetCaller)
	opts.Agent = "codex"
	put(t, root, "skills/example/state-schema.md", "# State ownership\nThis skill owns the store schema.\n", 0644)
	name := "skills/example/helper.sh"
	before := "#!/bin/sh\n# Owner: skills/example\nprintf 'same-behavior\\n'\n"
	after := "#!/bin/sh\n# Owner schema: skills/example/state-schema.md\nprintf 'same-behavior\\n'\n"
	put(t, root, name, before, 0755)
	proposed := proposal{Edits: []proposedEdit{{Path: name, BeforeDigest: digest([]byte(before)), Action: "replace", Content: after}}}
	plan, err := prepareWithProvider(context.Background(), opts, func(_ context.Context, _ string, request string) (proposal, AgentRun, error) {
		return proposed, AgentRun{}, nil
	})
	if err != nil {
		t.Fatal(err)
	}
	if _, err = plan.Apply(); err != nil {
		t.Fatal(err)
	}
	output, err := exec.Command(root + "/" + name).CombinedOutput()
	if err != nil || string(output) != "same-behavior\n" {
		t.Fatalf("helper behavior: %s %v", output, err)
	}
	if !reflect.DeepEqual(treeAt(t, root)[name].Content, []byte(after)) {
		t.Fatal("content adaptation differs")
	}
}

